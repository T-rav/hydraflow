class TestWikiSection:
    """Touched files -> keywords -> wiki topic-page entry match -> excerpts."""

    def test_matched_entries_are_bounded_to_max_wiki_in_document_order(
        self, tmp_path: Path
    ) -> None:
        _write_wiki_topic(
            tmp_path,
            "gotchas",
            entries=[
                ("Config validators are the source of truth", "Config objects rule."),
                ("Unrelated entry about pricing", "Pricing refresh notes."),
                ("Config schema evolution notes", "More about config schemas."),
                ("Config caching gotcha", "Caching config values safely."),
            ],
        )

        result = gather_decomposition_docs(
            ["src/config.py"], repo_root=tmp_path, max_adrs=3, max_wiki=2
        )

        assert "Config validators are the source of truth" in result
        assert "Config schema evolution notes" in result
        # Third matching entry is excluded by the max_wiki=2 bound.
        assert "Config caching gotcha" not in result
        # Non-matching entry never scored in the first place.
        assert "Unrelated entry about pricing" not in result
        assert result.count("### ") == 2

    def test_entries_matching_more_keywords_rank_above_earlier_weaker_matches(
        self, tmp_path: Path
    ) -> None:
        _write_wiki_topic(
            tmp_path,
            "patterns",
            entries=[
                ("Config only mention", "Talks about config alone."),
                (
                    "Config and manager both mentioned here",
                    "Talks about config and the pr manager together.",
                ),
            ],
        )

        result = gather_decomposition_docs(
            ["src/config.py", "src/pr_manager.py"],
            repo_root=tmp_path,
            max_adrs=3,
            max_wiki=1,
        )

        # Two-keyword match outranks the earlier one-keyword match even
        # though it appears later in the source document.
        assert "Config and manager both mentioned here" in result
        assert "Config only mention" not in result

    def test_index_page_is_never_scanned_for_entries(self, tmp_path: Path) -> None:
        wiki_dir = tmp_path / "docs" / "wiki"
        wiki_dir.mkdir(parents=True)
        (wiki_dir / "index.md").write_text(
            "# Wiki Index\n\n## Config wiki index heading\n\nShould never surface.\n"
        )

        result = gather_decomposition_docs(
            ["src/config.py"], repo_root=tmp_path, max_adrs=3, max_wiki=5
        )

        assert result == ""


