class TestGracefulFailure:
    def test_empty_touched_files_returns_empty_string(self, tmp_path: Path) -> None:
        assert gather_decomposition_docs([], repo_root=tmp_path) == ""

    def test_nonexistent_repo_root_returns_empty_without_raising(self) -> None:
        result = gather_decomposition_docs(
            ["src/config.py"], repo_root=Path("/nonexistent/hydraflow-test-root")
        )

        assert result == ""

    def test_repo_root_with_no_generated_docs_at_all_returns_empty(
        self, tmp_path: Path
    ) -> None:
        result = gather_decomposition_docs(["src/config.py"], repo_root=tmp_path)

        assert result == ""
